package org.azaadawaaz.app

import com.facebook.react.BaseReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.module.model.ReactModuleInfo
import com.facebook.react.module.model.ReactModuleInfoProvider
import org.azaadawaaz.app.modules.FilesModule
import org.azaadawaaz.app.modules.NetModule
import org.azaadawaaz.app.modules.P2PModule
import org.azaadawaaz.app.modules.PowModule
import org.azaadawaaz.app.modules.SodiumModule
import org.azaadawaaz.app.modules.TorModule
import org.azaadawaaz.app.modules.UpdateModule
import org.azaadawaaz.app.modules.VaultModule
import org.azaadawaaz.app.specs.NativeAzaadFilesSpec
import org.azaadawaaz.app.specs.NativeAzaadNetSpec
import org.azaadawaaz.app.specs.NativeAzaadP2PSpec
import org.azaadawaaz.app.specs.NativeAzaadPowSpec
import org.azaadawaaz.app.specs.NativeAzaadSodiumSpec
import org.azaadawaaz.app.specs.NativeAzaadTorSpec
import org.azaadawaaz.app.specs.NativeAzaadUpdateSpec
import org.azaadawaaz.app.specs.NativeAzaadVaultSpec

/** Registers the app's TurboModules (specs in src/native/specs, generated by codegen). */
class AzaadPackage : BaseReactPackage() {
  private val modules: Map<String, (ReactApplicationContext) -> NativeModule> =
    mapOf(
      NativeAzaadNetSpec.NAME to ::NetModule,
      NativeAzaadSodiumSpec.NAME to ::SodiumModule,
      NativeAzaadFilesSpec.NAME to ::FilesModule,
      NativeAzaadTorSpec.NAME to ::TorModule,
      NativeAzaadVaultSpec.NAME to ::VaultModule,
      NativeAzaadPowSpec.NAME to ::PowModule,
      NativeAzaadUpdateSpec.NAME to ::UpdateModule,
      NativeAzaadP2PSpec.NAME to ::P2PModule,
    )

  override fun getModule(name: String, reactContext: ReactApplicationContext): NativeModule? = modules[name]?.invoke(reactContext)

  override fun getReactModuleInfoProvider() = ReactModuleInfoProvider {
    modules.keys.associateWith { name -> ReactModuleInfo(name, name, false, false, false, true) }
  }
}
