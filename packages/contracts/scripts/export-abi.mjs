// Reads the forge build artifact and writes abi/AzaadAwaazRegistry.json (ABI array only) and
// src/abi.ts (the same ABI `as const`, so viem can infer types). Run after `forge build`.
// With --check it fails instead of writing when either file is out of date.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = join(root, "out", "AzaadAwaazRegistry.sol", "AzaadAwaazRegistry.json");
const check = process.argv.includes("--check");

let abi;
try {
  abi = JSON.parse(readFileSync(artifact, "utf8")).abi;
} catch (err) {
  console.error(`cannot read ${artifact}; run \`forge build\` first (${err.message})`);
  process.exit(1);
}
if (!Array.isArray(abi) || abi.length === 0) {
  console.error("artifact has no ABI");
  process.exit(1);
}

const json = JSON.stringify(abi, null, 2) + "\n";
const ts =
  "// Generated by scripts/export-abi.mjs from the forge artifact. Do not edit by hand.\n" +
  `export const registryAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

const targets = [
  [join(root, "abi", "AzaadAwaazRegistry.json"), json],
  [join(root, "src", "abi.ts"), ts],
];

let stale = false;
for (const [path, content] of targets) {
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // missing file: treat as out of date
  }
  if (current === content) continue;
  if (check) {
    console.error(`${path} is out of date; run \`pnpm --filter @azaadawaaz/contracts abi\``);
    stale = true;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
